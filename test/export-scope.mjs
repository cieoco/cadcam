import assert from 'node:assert/strict';
import {S,fresh,ex} from './_bench-setup.mjs';
import {prepareScopedExport,resolveExportScope} from '../js/blocks/export-scope.js';
import {fusionCandidates} from '../js/blocks/part-fusion.js';
import {f1AssemblyFixture} from './fixtures/f1-assembly-fixture.mjs';
import {faceFileExportData} from '../js/blocks/face-export.js';
import {exportLinksAsDxf} from '../js/blocks/exporters.js';
import {hydraulicSnapshot} from './fixtures/hinged-syringe.mjs';
const source=()=>({comps:S.comps,modules:S.modules,topo:S.topo,exportSettings:ex});
fresh('gear-gripper','fourbar-lift');
const initial=JSON.stringify(source()),focus=S.modules[1].id;
const second=prepareScopedExport(source(),{scope:'design',focus},'dxf');
assert.ok(second.files.length);
const firstIds=new Set(S.comps.filter(c=>c.moduleId!==focus).map(c=>c.id));
assert.ok(second.files.every(f=>!f.sourceIds.some(id=>firstIds.has(id))));
assert.equal(JSON.stringify(source()),initial,'preparing does not mutate');
const bar=S.comps.find(c=>c.moduleId===focus&&c.type==='bar');
const one=prepareScopedExport(source(),{scope:'selected',selectedId:bar.id},'dxf');
assert.equal(one.files.length,1);assert.deepEqual(one.files[0].sourceIds,[bar.id]);
S.topo.assemblyMembers=[S.modules[0].id];
assert.ok(resolveExportScope(source(),{scope:'assembly'}).targets.every(c=>c.moduleId!==focus));
assert.throws(()=>prepareScopedExport(source(),{scope:'selected'},'dxf'),/點選/);
assert.throws(()=>prepareScopedExport(source(),{scope:'design',focus:'#root'},'dxf'),/沒有/);
const plate=S.comps.find(c=>c.type==='triangle'),gear=fusionCandidates(S.comps,plate)[0];plate.fusedWith=gear.id;
for(const selectedId of [plate.id,gear.id])for(const format of ['svg','dxf']){
 const p=prepareScopedExport(source(),{scope:'selected',selectedId},format);
 assert.equal(p.files.length,1);assert.deepEqual(p.files[0].sourceIds,[gear.id,plate.id]);
}
const face=f1AssemblyFixture();face.topo ||= {params:face.params};
const data=faceFileExportData(face),baseline=[];
exportLinksAsDxf(data.comps,data.points,data.params,data.settings,data.mounts,data.extras,(text,name)=>baseline.push({text,name}));
const child=face.modules.find(m=>m.mount),childPart=face.comps.find(c=>c.moduleId===child.id&&c.type==='triangle');
const childOut=prepareScopedExport(face,{scope:'selected',selectedId:childPart.id},'dxf');
assert.equal(childOut.files.length,1);
assert.equal(childOut.files[0].text,baseline.find(f=>f.name===childOut.files[0].name).text,'mount holes match the existing face exporter');
const h=structuredClone(hydraulicSnapshot);h.topo={params:h.params};h.modules ||= [];
const hf=prepareScopedExport(h,{scope:'selected',selectedId:'HArm'},'dxf');
assert.equal(hf.files.length,1);
console.log('PASS scoped export: design isolation, selection, assembly membership, fusion, mounted hole parity, hydraulic, no mutation');
