import assert from 'node:assert/strict';
import { getExample } from '../js/blocks/examples.js';
import { buildVideoEvidence } from '../js/blocks/video-evidence.js';
const source=structuredClone(getExample('slider-crank').snapshot);
source.params.LL1=40; source.params.LL2=88;
const input={...source,version:'test-version',lessonId:'slider80'};
const before=JSON.stringify(input);
const proof=buildVideoEvidence(input);
assert.ok(proof.lines.some(l=>l.includes('80.0 mm')));
assert.ok(proof.lines.some(l=>l.includes('40.0 mm')&&l.includes('88.0 mm')));
assert.ok(proof.lines.some(l=>l.includes('test-version')));
assert.equal(JSON.stringify(input),before);
source.params.LL1=32;
assert.throws(()=>buildVideoEvidence(input),/錄影前重驗未通過/);
assert.ok(proof.lines.some(l=>l.includes('80.0 mm')),'evidence is a captured value');
const ordinary=buildVideoEvidence({...input,lessonId:null});
assert.equal(ordinary.lines.length,1); assert.match(ordinary.lines[0],/未附任務驗證/);
assert.throws(()=>buildVideoEvidence({...input,comps:[]}),/錄影前重驗未通過/);
console.log('PASS fresh video evidence, dimensions, version, nonmutation and no generic pass badge');
