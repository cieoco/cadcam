import assert from 'node:assert/strict';
import {inspectMountingChange} from '../js/blocks/mounting-review.js';
import {confirmMountingChange,commitMountingEdit,mountingCandidate} from '../js/blocks/mounting-review-ui.js';
import {normalizeSnapshot,toSnapshot} from '../js/blocks/schema.js';
import {getExample} from '../js/blocks/examples.js';
import {pivotTurntableSnapshot} from '../js/blocks/disk-turntable-example.js';
import {tabNutFixture,tabNutRequest} from './fixtures/tab-nut-fixture.mjs';
import {buildFaceCandidate} from '../js/blocks/face-candidate.js';
import {planSyringeStroke} from '../js/blocks/syringe-operations.js';
import {FABRICATION_DEFAULTS} from '../js/blocks/fabrication-profile.js';
import {bracketFixture} from './fixtures/face-bracket-fixture.mjs';
const clone=structuredClone;
const base=normalizeSnapshot(getExample('hydraulic-h07').snapshot);
const syringe=s=>s.comps.find(c=>c.type==='syringe');
const inspect=(source,edit)=>{const next=clone(source);edit(next);return inspectMountingChange(source,next);};
assert.equal(inspectMountingChange(base,clone(base)).changes.length,0);
assert.ok(inspect(base,s=>syringe(s).a.u+=3).changes.length,'clamp placement changes base drilling');
assert.ok(inspect(base,s=>syringe(s).axisDeg+=10).changes.length,'fixed two-hole mount turns its drilling');
assert.equal(inspect(base,s=>{syringe(s).installation.barrelOffsetMm+=5;}).changes.length,0,'sliding barrel inside clamp keeps base holes');
for(const source of [base,normalizeSnapshot(pivotTurntableSnapshot)]){
  const result=planSyringeStroke(source.comps,source.params,syringe(source).id,10);
  assert.ok(result.ok,result.message);
  const reviewed=inspectMountingChange(source,{...source,comps:result.comps});
  assert.equal(reviewed.changes.length,0,'simulation must not ask to drill');
  assert.equal(inspect(source,s=>s.comps.forEach(c=>['p1','p2','p3'].forEach(k=>{if(c[k]){c[k].x+=37;c[k].y-=21;}}))).changes.length,0,'whole design translation keeps local holes');
}
let questions=0;
const changed=clone(base);syringe(changed).a.u+=3;
assert.equal(confirmMountingChange(base,changed,{ask:()=>{questions++;return false;}}),false);
assert.equal(questions,1);
assert.equal(confirmMountingChange(base,base,{ask:()=>{throw Error('unnecessary question');}}),true);
const state={comps:clone(base.comps),modules:clone(base.modules||[]),topo:{params:clone(base.params)},fabrication:clone(base.fabrication)};
const before=JSON.stringify(state),undos=[];
globalThis.window={confirm:()=>false,alert:message=>{throw Error(message);}};
assert.equal(commitMountingEdit(state,d=>syringe(d).a.u+=3,{pushUndo:()=>undos.push(JSON.stringify(state))}),false);
assert.equal(JSON.stringify(state),before);assert.equal(undos.length,0);
window.confirm=()=>true;
assert.equal(commitMountingEdit(state,d=>syringe(d).a.u+=3,{pushUndo:()=>undos.push(JSON.stringify(state))}),true);
assert.deepEqual(undos,[before]);
const reopened=normalizeSnapshot(toSnapshot(state.comps,state.topo,base.counter,state));
assert.equal(inspectMountingChange({...base,comps:state.comps,params:state.topo.params},reopened).changes.length,0,'saved layout becomes baseline');
Object.assign(state,JSON.parse(undos.pop()));assert.equal(JSON.stringify(state),before);
const source=tabNutFixture(),request=tabNutRequest(),mounted=buildFaceCandidate(source,request);
assert.ok(mounted.ok,mounted.reason);
const next=buildFaceCandidate(mounted.work,{...request,reselect:true,selection:{...request.selection,offsetU:5}});
assert.ok(next.ok,next.reason);
assert.ok(inspectMountingChange(mounted.work,next.work).changes.length,'tab-nut interface relocation uses same review');
assert.equal(inspectMountingChange(source,mounted.work).changes.length,0,'first installation already confirms drilling');
const bracketSource=bracketFixture(),bracketRequest={childId:'Child',hostEndpoint:{moduleId:'Host',outputId:'plate',partId:'HostBar'},childEndpoint:{partId:'frame'},selection:{hostFace:'top',childFace:'back',alignU:0,alignV:0,offsetU:0,offsetV:0,gap:0,quarterTurns:1,brackets:{enabled:true,offsets:{},childPart:'frame'}}};
const bracket=buildFaceCandidate(bracketSource,bracketRequest);assert.ok(bracket.ok,bracket.reason);
const shifted=buildFaceCandidate(bracket.work,{...bracketRequest,reselect:true,selection:{...bracketRequest.selection,offsetU:5}});assert.ok(shifted.ok,shifted.reason);
assert.ok(inspectMountingChange(bracket.work,shifted.work).changes.length,'bracket mounting uses same comparison');
const motor={comps:[{type:'bar',id:'Arm',isInput:true,fixedLen:true,motorType:'tt',physicalMotor:'1',p1:{id:'A',type:'fixed',x:0,y:0,physicalMotor:'1'},p2:{id:'B',type:'floating',x:80,y:0},lenParam:'L',motorMount:{center:'A',motor:'1',outputBody:'Arm',face:'back',orientation:'horizontal'}},{type:'anchor',id:'Foot',p1:{id:'F',type:'fixed',x:100,y:0}}],params:{L:80},modules:[],fabrication:clone(FABRICATION_DEFAULTS)};
assert.ok(inspect(motor,s=>s.comps[0].motorMount.orientation='vertical').changes.length,'motor orientation uses the real mounting pattern');
assert.ok(inspect(motor,s=>s.fabrication.ttMount.screwSpacingMm+=1).changes.length,'machining profile moves paired holes');
assert.ok(inspect(motor,s=>s.comps[0].motorType='mg995').changes.length,'motor replacement changes mounting pattern');
assert.equal(inspect(motor,s=>{s.params.L=100;s.comps[0].p2.x=100;}).changes.length,0,'unconnected arm length does not move motor mounting holes');
assert.equal(inspect(base,s=>s.comps.push({type:'anchor',id:'Elsewhere',p1:{id:'Z',type:'fixed',x:500,y:500}})).changes.length,0,'unrelated holes do not prompt for a clamp');
assert.equal(inspect(base,s=>syringe(s).a.u=10000).ok,false,'unavailable paired-hole geometry blocks acceptance');
const gripper=normalizeSnapshot(getExample('gear-gripper').snapshot);
assert.ok(inspect(gripper,s=>s.params.GPRA+=1).changes.some(c=>c.label==='齒輪與桿件兩孔'));
assert.equal(inspect(gripper,s=>s.params.LJ_tip+=1).changes.length,0,'jaw tip dimensions leave its paired holes alone');
const child=mounted.work.comps.filter(c=>c.moduleId==='Child'),childEdit=clone(child);childEdit[0].p2.x+=10;
const complete=mountingCandidate(mounted.work,{comps:childEdit,params:{...mounted.work.params,CL:70}},child);
assert.deepEqual(complete.comps.filter(c=>c.moduleId!=='Child'),mounted.work.comps.filter(c=>c.moduleId!=='Child'));
assert.ok(inspectMountingChange(mounted.work,complete).changes.length,'focused part edit still checks its cross-module interface');
console.log('mounting review: candidate cancel/accept/undo/reopen, clamp, motion and tab-nut passed');
