import assert from 'node:assert/strict';
import {planMotorInstallation} from '../js/blocks/actuator-installation.js';
import {planWheel} from '../js/blocks/wheel.js';
import {compileTopology} from '../js/core/topology.js';
import {solveTopology} from '../js/multilink/solver.js';
import {motionPoseIssue,inspectMotionRange} from '../js/blocks/solve-health.js';
import {createSimulationScope} from '../js/blocks/simulation-scope.js';

const base=planMotorInstallation({comps:[],params:{},modules:[]},{type:'tt',hostId:'world',motorId:'1',face:'back',orientation:'horizontal',position:{x:10,y:20}});
assert.ok(base.ok,base.message);
const wheel=planWheel({...base,modules:[]},{motorId:base.comps[0].id});
assert.ok(wheel.ok,wheel.message);
const mixed=planMotorInstallation({...wheel,modules:[]},{type:'tt',hostId:'world',motorId:'2',face:'back',orientation:'horizontal',position:{x:150,y:20}});
assert.ok(mixed.ok,mixed.message);
const topo={params:mixed.params};
const scope=createSimulationScope({comps:mixed.comps,modules:[],topo,compiled:compileTopology(mixed.comps,topo,new Set()),assembly:null,mode:'design',designFocus:null});
const solveAt=a=>solveTopology(scope.compiled,{thetaDeg:a,motorAngles:{1:a,2:0}});
const before=JSON.stringify(mixed.comps);
for(const a of [0,45,90,180,359])assert.equal(motionPoseIssue(scope.moving,solveAt(a)),null);
assert.ok(inspectMotionRange({comps:scope.moving,solveAt,theta:0,plan:{mode:'spin'},activeMotor:'1'}).ok);
const disk=mixed.comps.find(c=>c.wheelWidthMm),loose=mixed.comps.find(c=>c.type==='motor');
assert.notDeepEqual(solveAt(0).points[disk.p2.id],solveAt(90).points[disk.p2.id]);
assert.equal(JSON.stringify(mixed.comps),before,'range checks do not change the loose motor or work');
assert.equal(inspectMotionRange({comps:scope.moving,solveAt,theta:0,plan:{mode:'spin'},activeMotor:'2'}).code,'unconnected_motor');
assert.deepEqual(motionPoseIssue(scope.moving,solveAt(0),{activeMotor:'2'}).componentIds,[loose.id]);
assert.equal(motionPoseIssue([loose],{isValid:true,points:{}}).code,'unconnected_motor');
assert.equal(motionPoseIssue(scope.moving,{isValid:true,points:{}}).code,'missing_points');
assert.equal(motionPoseIssue(scope.moving,{...solveAt(0),isUnderconstrained:true,unresolvedPointIds:[disk.p2.id]}).code,'underconstrained');
assert.equal(motionPoseIssue(scope.moving,{isValid:false,errorReason:'geometry failure'}).message,'geometry failure');
console.log('Loose motor playback: connected TT wheel moves; loose active motor and real solve failures remain blocked');
