import assert from 'node:assert/strict';
import {builtinTemplate,instantiateTemplate} from '../js/blocks/module-ops.js';
import {FABRICATION_DEFAULTS} from '../js/blocks/fabrication-profile.js';
import {buildFaceCandidate,faceCandidateModel,validateFaceCandidate} from '../js/blocks/face-candidate.js';
import {inspectRackExport} from '../js/blocks/exporters.js';
import * as Exporters from '../js/blocks/exporters.js';
import {readConnectionDescriptor} from '../js/blocks/connection-descriptor.js';
import {faceFileExportData,validateFaceExport,faceBuildPackHtml,usesFaceExport} from '../js/blocks/face-export.js';
import {toSnapshot,normalizeSnapshot} from '../js/blocks/schema.js';
import {retainedSceneKey} from '../js/blocks3d/scene-reuse.js';
import {mkdirSync,writeFileSync} from 'node:fs';
const host=instantiateTemplate(builtinTemplate('rack-lift'),{counter:0,place:{x:0,y:0}});
const child=instantiateTemplate(builtinTemplate('gear-gripper'),{counter:2,place:{x:250,y:0},usedMotorIds:['1']});
const source={comps:[...host.comps,...child.comps],modules:[host.module,child.module],params:{...host.params,...child.params},fabrication:structuredClone(FABRICATION_DEFAULTS)};
source.fabrication.cnc.stockThicknessMm=4;
const request={childId:child.module.id,hostEndpoint:{moduleId:host.module.id,outputId:'carriage'},childEndpoint:{partId:'frame'},selection:{hostFace:'top',childFace:'bottom',alignU:0,alignV:0,offsetU:0,offsetV:0,gap:0,quarterTurns:0}};
const before=JSON.stringify(source),candidate=buildFaceCandidate(source,request);
assert.ok(candidate.ok,candidate.reason);
assert.equal(JSON.stringify(source),before);
const rack=source.comps.find(c=>c.type==='rack'),pinion=source.comps.find(c=>c.id===rack.pinion);
let shapeKey;
for(const theta of [0,20,40]){
 const pose={theta,motorAngles:{'1':theta,'2':10}},scene=faceCandidateModel(candidate,pose);
 assert.ok(scene.solveValidity.valid);
 const material=scene.model.materialParts.find(p=>p.partId===rack.id),exported=inspectRackExport(rack,source.params,pinion);
 assert.ok(material,'the real rack must have one common material');
 assert.deepEqual(material.geometry.outlines,[exported.outline]);
 assert.deepEqual(material.geometry.cutouts.map(c=>c.points),exported.cutouts.map(c=>c.points));
 assert.equal(material.geometry.thicknessMm,4);
 assert.equal(scene.model.racks.find(r=>r.id===rack.id).materialPartId,rack.id);
 assert.ok(!scene.model.geometryDiagnostics.some(d=>d.sourceIds?.includes(rack.id)));
 for(const hole of material.geometry.holes){
  const m=material.pose.matrix,p=scene.points[hole.id];assert.ok(p);
  assert.ok(Math.abs(m[0]*hole.x+m[4]*hole.y+m[12]-p.x)<.005);
  assert.ok(Math.abs(m[1]*hole.x+m[5]*hole.y+m[13]-p.y)<.005,'rack holes follow solved travel, not their home position');
 }
 const key=retainedSceneKey(scene.model);assert.ok(key);if(shapeKey)assert.equal(key,shapeKey);shapeKey=key;
 const checked=await validateFaceCandidate(candidate,pose);
 assert.ok(checked.saveable,checked.reason);
}
const descriptor=readConnectionDescriptor({...candidate.work,childId:child.module.id});
assert.equal(descriptor.capabilities.geometry,true);assert.equal(descriptor.capabilities.drilling,false);
assert.ok(descriptor.diagnostics.some(d=>d.code==='rack_drilling_not_supported'));
const unsupported=buildFaceCandidate(source,{...request,selection:{...request.selection,hostFace:'back',quarterTurns:1,brackets:{enabled:true,offsets:{},childPart:'frame'}}});
assert.equal(unsupported.ok,false);assert.match(unsupported.reason,/齒條角碼開孔尚未支援/);
assert.equal((await validateFaceCandidate(unsupported)).saveable,false);
assert.equal((await validateFaceExport(unsupported.work,{theta:0})).ok,false,'unsupported requested drilling cannot bypass the export guard');
const changed=structuredClone(source);changed.comps.find(c=>c.id===rack.id).stock={thicknessMm:6};
const changedModel=faceCandidateModel(buildFaceCandidate(changed,request),{theta:20});
assert.equal(changedModel.catalog.parts[rack.id].thicknessMm,6);
assert.notEqual(retainedSceneKey(changedModel.model),shapeKey);
const blobs=new Map(),downloads=[];let seq=0;
globalThis.document={body:{appendChild(){}},createElement:()=>({click(){downloads.push({name:this.download,blob:blobs.get(this.href)});},remove(){}})};
URL.createObjectURL=blob=>{const key=`blob:${seq++}`;blobs.set(key,blob);return key;};URL.revokeObjectURL=()=>{};globalThis.setTimeout=()=>0;
const exportRack=async work=>{
 const d=faceFileExportData(work,{theta:20}),start=downloads.length;
 Exporters.exportLinksAsSvg(d.comps,d.points,d.params,d.settings,d.mounts,d.extras);
 Exporters.exportLinksAsDxf(d.comps,d.points,d.params,d.settings,d.mounts,d.extras);
 return Promise.all(downloads.slice(start).filter(f=>f.name===rack.id+'.svg'||f.name===rack.id+'.dxf').map(async f=>({name:f.name,text:await f.blob.text()})));
};
const saved=toSnapshot(candidate.work.comps,candidate.work.topo,0,{modules:candidate.work.modules,fabrication:source.fabrication});
const reopened=normalizeSnapshot(saved),files=await exportRack(candidate.work);
assert.equal(files.length,2);assert.deepEqual(await exportRack(reopened),files);
for(const file of files)for(const hole of rack.holes)assert.ok(file.text.includes(hole.id),'actual SVG/DXF contains rack hole identity');
assert.ok(usesFaceExport(candidate.work));
const pack=await validateFaceExport(candidate.work,{theta:20});assert.ok(pack.ok,pack.reason);
assert.ok(pack.plan.parts.some(p=>p.name===rack.id));assert.ok(faceBuildPackHtml(pack).includes('manufacturingTrace'));
mkdirSync('output/framework-stabilization/w4b-rack',{recursive:true});
writeFileSync('output/framework-stabilization/w4b-rack/ui-unmounted.blocks.json',JSON.stringify(toSnapshot(source.comps,{params:source.params},0,{modules:source.modules,fabrication:source.fabrication}),null,2));
writeFileSync('output/framework-stabilization/w4b-rack/ui-mounted.blocks.json',JSON.stringify(saved,null,2));
console.log('F2 rack: shared shape/slots/stock, independent moving holes, stable pose cache, immutable candidate, explicit unsupported drilling, save/open and public SVG/DXF/pack');
