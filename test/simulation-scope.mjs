import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {createSimulationScope} from '../js/blocks/simulation-scope.js';
import {normalizeSnapshot} from '../js/blocks/schema.js';
import {compileTopology} from '../js/core/topology.js';
import {solveTopology} from '../js/multilink/solver.js';
import {planMotion} from '../js/blocks/motion.js';
import {planTippingBucket} from '../js/blocks/tipping-bucket-workflow.js';
const fixture=normalizeSnapshot(JSON.parse(readFileSync(new URL('./fixtures/design-simulation.json',import.meta.url))));
const before=JSON.stringify(fixture);
const state={...fixture,topo:{params:fixture.params},mode:'design',designFocus:'#root',assembly:{sentinel:true}};
state.compiled=compileTopology(state.comps,state.topo,new Set());
const root=createSimulationScope(state);
assert.equal(root.comps.length,4);
assert.equal(root.assembly,null);
assert.equal(root.wholeWork,false);
assert.equal(planTippingBucket(fixture).ok,false,'whole-work bucket contract rejects this mixed work');
let sol=solveTopology(root.compiled,{thetaDeg:0,motorAngles:{'2':0}});
assert.equal(sol.isValid,true);
const plan=planMotion(root.compiled,state.topo,0,sol.points,{active:'2',frozen:{'1':0}});
assert.equal(plan.mode,'rock','user four-bar is not a full-rotation linkage');
assert.ok(plan.lo<0&&plan.hi>0);
for(let a=plan.lo;a<=plan.hi;a+=2){
  sol=solveTopology(root.compiled,{thetaDeg:a,motorAngles:{'2':a},_prevPoints:sol.points});
  assert.equal(sol.isValid,true,`local angle ${a}`);
  for(const c of root.comps)assert.ok(Math.abs(Math.hypot(sol.points[c.p1.id].x-sol.points[c.p2.id].x,sol.points[c.p1.id].y-sol.points[c.p2.id].y)-fixture.params[c.lenParam])<.001);
}
const broken=structuredClone(state);broken.topo.params.BucketBase=-1;
assert.equal(solveTopology(createSimulationScope(broken).compiled,{thetaDeg:0,motorAngles:{'2':0}}).isValid,true);
const side=createSimulationScope({...state,designFocus:'RightSide'});
assert.ok(side.comps.every(c=>c.moduleId==='RightSide'));
assert.ok(side.comps.every(c=>!c.isInput));
const bench=createSimulationScope({...state,mode:'bench'});
assert.equal(bench.compiled,state.compiled);assert.equal(bench.assembly,state.assembly);assert.equal(bench.wholeWork,true);
assert.equal(JSON.stringify(fixture),before,'scope must not mutate saved work');
console.log('PASS isolated user four-bar, rigid lengths, hidden invalid module, static tab and bench boundary');

const {assemblyBranch,closedAssemblies,closedAssemblyIds}=await import('../js/blocks/assembly-view.js');
assert.deepEqual([...assemblyBranch(fixture.modules,'Driver')].sort(),['Back','Driver','Floor','RightSide']);
closedAssemblies.add('Driver');
assert.equal(closedAssemblyIds(fixture.modules).size,4);
assert.equal(createSimulationScope({...state,mode:'bench'}).comps.length,state.comps.length,'closing a view must not change validation scope');
assert.equal(JSON.stringify(fixture),before,'closing preserves snapshot');
closedAssemblies.clear();assert.equal(closedAssemblyIds(fixture.modules).size,0);
console.log('PASS assembly view close/reopen preserves work and validation scope');

const {assemblyWork,changeAssemblyMembership,normalizeAssemblyMembers}=await import('../js/blocks/assembly-membership.js');
const {toSnapshot}=await import('../js/blocks/schema.js');
const {encodeSnapshot,decodeShareString}=await import('../js/share-codec.js');
const removed=changeAssemblyMembership(fixture.comps,fixture.modules,{},'#root',false);
assert.deepEqual(removed.members,['Driver','RightSide','Floor','Back']);
const topo={...state.topo,assemblyMembers:removed.members};
const kept=assemblyWork(fixture.comps,fixture.modules,topo);
assert.equal(kept.comps.length,9);
assert.ok(kept.comps.every(c=>c.moduleId));
assert.equal(createSimulationScope({...state,topo,mode:'bench'}).comps.length,9);
assert.equal(createSimulationScope({...state,topo,mode:'design'}).comps.length,4,'removed design remains editable');
const serialized=toSnapshot(fixture.comps,topo,fixture.counter,{modules:fixture.modules,fabrication:fixture.fabrication});
const reopened=normalizeSnapshot(decodeShareString(encodeSnapshot(serialized)));
assert.deepEqual(reopened.assemblyMembers,removed.members);
assert.equal(reopened.comps.length,fixture.comps.length,'saving never deletes excluded designs');
assert.deepEqual(reopened.modules,fixture.modules,'internal mounts survive');
const readded=changeAssemblyMembership(fixture.comps,fixture.modules,topo,'#root',true);
assert.equal(assemblyWork(fixture.comps,fixture.modules,{assemblyMembers:readded.members}).comps.length,fixture.comps.length);
const group=changeAssemblyMembership(fixture.comps,fixture.modules,{},'Floor',false);
assert.deepEqual(group.members,['#root'],'removing child takes full connected family');
assert.equal(group.affected.length,4);
assert.deepEqual(normalizeAssemblyMembers(['Floor','missing','Floor'],fixture.comps,fixture.modules),removed.members);
assert.equal(normalizeAssemblyMembers(undefined,fixture.comps,fixture.modules),undefined,'legacy all preserved');
assert.deepEqual(assemblyWork(fixture.comps,fixture.modules,{assemblyMembers:[]}),{comps:[],modules:[]});
const onlyRoot=createSimulationScope({...state,mode:'bench',topo:{...state.topo,assemblyMembers:['#root']}});
assert.equal(onlyRoot.modules.length,0);
assert.equal(solveTopology(onlyRoot.compiled,{thetaDeg:0,motorAngles:{'2':0}}).isValid,true);
assert.equal(JSON.stringify(fixture),before,'membership operations are pure');
console.log('PASS explicit membership, family closure, legacy migration, save/share/reopen, independent simulation');
const {mergeAssemblyWork}=await import('../js/blocks/assembly-membership.js');
const changed=structuredClone(kept);changed.comps[0].color='#112233';
const merged=mergeAssemblyWork(fixture.comps,fixture.modules,topo,changed);
assert.equal(merged.comps.length,fixture.comps.length);
assert.equal(merged.comps[0].color,'#112233');
assert.deepEqual(merged.comps.filter(c=>!c.moduleId),fixture.comps.filter(c=>!c.moduleId),'candidate commit keeps excluded drawings');
assert.equal(JSON.stringify(fixture),before);
const {faceCandidateModel}=await import('../js/blocks/face-candidate.js');
const scene=faceCandidateModel({work:{...kept,topo,fabrication:fixture.fabrication}},{theta:0,motorAngles:{'1':0}});
assert.equal(scene.solveValidity.valid,true,'bucket candidate ignores unrelated four-bar');
assert.ok(scene.model.materialParts.every(p=>!p.id?.startsWith('Link2')));
console.log('PASS candidate scope and merge preserve excluded designs');
const {validateAssemblyTask}=await import('../js/blocks/assembly-task-validation.js');
const {getExample}=await import('../js/blocks/examples.js');
for(const id of ['gear-gripper','parallel-fourbar']){
  const source=structuredClone(getExample(id).snapshot);
  assert.equal(validateAssemblyTask(source).ok,true,`${id} task remains checked`);
  if(id==='gear-gripper')source.params.gripperObjectWidth=999;else source.params.parallelEndHeight=999;
  assert.equal(validateAssemblyTask(source).ok,false,`${id} invalid task cannot bypass validation`);
  assert.equal(validateAssemblyTask({...source,comps:fixture.comps.filter(c=>!c.moduleId)}),null,'excluded task does not block unrelated four-bar');
}
console.log('PASS scoped teaching tasks retain validation and ignore removed tasks');
