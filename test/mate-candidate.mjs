import assert from 'node:assert/strict';
import {createMateCandidate} from '../js/blocks/mate-candidate.js';
import {f1AssemblyFixture} from './fixtures/f1-assembly-fixture.mjs';
import {freezeData} from '../js/blocks/face-candidate.js';
import {connect} from '../js/blocks/bench.js';
const source=f1AssemblyFixture();source.topo={params:source.params};
let pose={theta:0,motorAngles:{'2':0}},changes=0;
const before=JSON.stringify(source);freezeData(source);
const candidate=createMateCandidate({readSource:()=>source,readPose:()=>pose,onChange:()=>changes++});
candidate.set({comps:source.comps,modules:source.modules});
assert.ok(candidate.snapshot().scene.model.materialParts.length);
assert.equal(candidate.take(),null,'pending check cannot commit');
await new Promise(r=>setTimeout(r,400));
assert.equal(changes,1);assert.ok(candidate.snapshot().result.saveable);
const result=candidate.take();assert.ok(result);assert.equal(candidate.take(),null,'only one commit');
assert.equal(JSON.stringify(source),before,'preview and confirmation do not mutate source');
candidate.set({comps:source.comps,modules:source.modules});candidate.cancel();
await new Promise(r=>setTimeout(r,100));assert.equal(candidate.snapshot(),null);assert.equal(changes,1,'cancel ignores late validation');
candidate.set({comps:source.comps,modules:source.modules});pose={theta:20};
await new Promise(r=>setTimeout(r,100));assert.equal(candidate.take(),null,'changed pose refuses stale confirmation');
assert.equal(JSON.stringify(source),before);
const legacy=structuredClone(source),child=legacy.modules.find(m=>m.mount),host=legacy.modules.find(m=>m.id===child.mount.to.module);
child.mount=null;const brace=legacy.comps.find(c=>c.moduleId===host.id&&c.id.startsWith('ToolBrace'));
const joined=connect(legacy.comps,legacy.modules,child.id,{module:host.id,port:`edge:${brace.id}:R`},legacy.params,{activeMotor:'1',theta:0,motorAngles:{'2':0}},{joint:'bracket-m3'});
assert.ok(joined.ok);const original=JSON.stringify(legacy);
const old=createMateCandidate({readSource:()=>legacy,readPose:()=>({theta:0})});
old.set(joined);await new Promise(r=>setTimeout(r,400));assert.ok(old.snapshot().result.saveable,'actual along-edge material preview can commit');
assert.equal(JSON.stringify(legacy),original);legacy.topo.params.extra=1;assert.equal(old.take(),null,'same-ID parameter edits invalidate candidate');
console.log('isolated mate candidate: immutable source, actual material model, pending/stale/cancel/one commit');
