import assert from 'node:assert/strict';
import {designGuideStep,guideFrameCandidate} from '../js/blocks/design-guide.js';
const rod={id:'rod',type:'bar',lenParam:'L',fixedLen:true,p1:{id:'a',type:'floating',x:0,y:0},p2:{id:'b',type:'floating',x:80,y:0}};
assert.equal(designGuideStep([]).stage,'draw');
assert.equal(designGuideStep([{type:'anchor',p1:{id:'a',type:'fixed'}}]).stage,'draw');
assert.equal(designGuideStep([rod]).stage,'frame');
let result=guideFrameCandidate([rod],{componentId:'rod'});
assert.equal(result.ok,true);assert.equal(rod.p1.type,'floating');
assert.equal(result.comps[0].p1.type,'fixed');assert.equal(result.comps[0].p2.type,'fixed');
assert.equal(result.comps[0].p2.x,80);assert.equal(designGuideStep(result.comps).stage,'draw');
const input={...rod,isInput:true};
assert.equal(guideFrameCandidate([input],{componentId:'rod'}).ok,false);
assert.equal(guideFrameCandidate([rod],{nodeId:'missing'}).ok,false);
assert.equal(guideFrameCandidate([rod],{}).ok,false);
result=guideFrameCandidate([rod],{nodeId:'a',positions:{a:{x:5,y:8}}});
assert.equal(result.comps[0].p1.x,5);assert.equal(result.comps[0].p2.type,'floating');
assert.equal(designGuideStep(result.comps).stage,'drive');
const groundedInput={...input,p1:{...rod.p1,type:'fixed'}};
assert.equal(designGuideStep([groundedInput]).stage,'try');
assert.equal(designGuideStep([rod]).stage,'frame','a separate design is unaffected by another design motor');
console.log('PASS guide stages, frame candidates, selection guard, dimensions and original immutability');
