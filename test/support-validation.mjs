import {validateSupports} from '../js/blocks/support-validation.js';
import {tippingBucketSnapshot} from '../js/blocks/tipping-bucket-example.js';
import {planTippingBucket} from '../js/blocks/tipping-bucket-workflow.js';
import {check,report} from './_harness.mjs';
const source=structuredClone(tippingBucketSnapshot),before=JSON.stringify(source);
const inspect=change=>{const w=structuredClone(source);change(w);return validateSupports(w);};
const valid=validateSupports(source);
check('固定支架宣告存在仍非實體通過',valid.ok&&!valid.physicalVerified&&valid.motors[0].status==='fixed_frame_declared');
check('理想固定支點明列',valid.fixedPoints.some(p=>p.id==='O'&&p.status==='ideal_fixed'));
check('缺少指定支架拒絕',!inspect(w=>w.comps=w.comps.filter(c=>c.id!=='Support')).ok);
check('機架與輸出同體拒絕',!inspect(w=>w.comps.find(c=>c.id==='Drive').motorMount.frameBody='Drive').ok);
check('共用兩孔的活動板不能當外殼固定件',!inspect(w=>w.comps.find(c=>c.id==='Drive').motorMount.frameBody='LeftSide').ok);
check('浮動支架拒絕',!inspect(w=>w.comps.find(c=>c.id==='Support').p1.type='floating').ok);
check('退化固定桿拒絕',!inspect(w=>{const c=w.comps.find(c=>c.id==='Support');c.p1.x=c.p2.x;c.p1.y=c.p2.y;}).ok);
check('未指定機架僅可理想模擬',inspect(w=>delete w.comps.find(c=>c.id==='Drive').motorMount.frameBody).issues.some(i=>i.code==='IDEAL_MOTOR_SUPPORT'));
check('輸出宣告錯誤拒絕',!inspect(w=>w.comps.find(c=>c.id==='Drive').motorMount.outputBody='Support').ok);
check('軸心宣告錯誤拒絕',!inspect(w=>w.comps.find(c=>c.id==='Drive').motorMount.center='missing').ok);
const plan=planTippingBucket(source);check('教學共同操作附同一固定報告',plan.ok&&plan.validation.support.status==='unverified');
const bad=structuredClone(source);bad.comps.find(c=>c.id==='Support').p1.type='floating';check('翻斗任務拒絕浮動機架',!planTippingBucket(bad).ok);
check('檢查不變更作品',JSON.stringify(source)===before);
check('空作品及null不拋錯',validateSupports(null).ok&&validateSupports({}).ok);
report('support-validation');
