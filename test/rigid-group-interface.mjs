import {tippingBucketSnapshot} from '../js/blocks/tipping-bucket-example.js';
import {createRigidGroup} from '../js/blocks/rigid-groups.js';
import {prepareRigidGroupInterface as prepare, createRigidGroupInterfaceSession} from '../js/blocks/rigid-group-interface.js';
import {validateTippingBucketAssembly as validate} from '../js/blocks/tipping-bucket-assembly-validation.js';
import {faceCandidateModel} from '../js/blocks/face-candidate.js';
import {encodeSnapshot,decodeShareString} from '../js/share-codec.js';
import {normalizeSnapshot} from '../js/blocks/schema.js';
import {check,report} from './_harness.mjs';
const source=structuredClone(tippingBucketSnapshot);
source.modules=createRigidGroup(source.comps,source.modules,'Driver','side','料斗').modules;
const before=JSON.stringify(source), req=(action,hostId='RigidGroup',target)=>({operationVersion:1,action,hostId,groupId:'group-side',...(target?{target}:{})});
const extracted=prepare(source,req('extract','Driver'));
check('抽離候選且來源不變',extracted.ok&&JSON.stringify(source)===before);
const work=extracted.candidateSnapshot;
const parts=(w,a)=>faceCandidateModel({work:w},{theta:a,motorAngles:{'1':a}}).model.materialParts.filter(p=>['LeftSide','Floor-frame','RightSide-frame','Back-frame'].includes(p.partId));
for(const a of [0,-50,-100]) {
 const x=parts(source,a),y=parts(work,a);
 check(`抽離前後${a}度板件姿態相同`,x.every(p=>p.pose.matrix.every((v,i)=>Math.abs(v-y.find(q=>q.partId===p.partId).pose.matrix[i])<1e-7)));
}
check('支架與驅動桿未改動',JSON.stringify(source.comps.filter(c=>['Drive','Support'].includes(c.id)))===JSON.stringify(work.comps.filter(c=>['Drive','Support'].includes(c.id))));
check('新結構通過完整料斗驗證',validate(work).ok);
const detached=prepare(work,req('detach'));
check('整組拆下保留內部接合',detached.ok&&detached.candidateSnapshot.modules.filter(m=>m.mount?.face).length===3);
check('拆下後四板不跟隨馬達',JSON.stringify(parts(detached.candidateSnapshot,0))===JSON.stringify(parts(detached.candidateSnapshot,-100)));
check('拆下狀態仍可驗證',validate(detached.candidateSnapshot).ok);
const attached=prepare(detached.candidateSnapshot,req('attach','RigidGroup',{module:'Driver',output:'side'}));
check('裝回通過驗證',attached.ok&&validate(attached.candidateSnapshot).ok);
check('裝回恢復原運動',JSON.stringify(parts(attached.candidateSnapshot,-50))===JSON.stringify(parts(work,-50)));
check('JSON正規化保留群組',normalizeSnapshot(JSON.parse(JSON.stringify(work))).modules.find(m=>m.id==='RigidGroup').rigidGroups.length===1);
check('重複抽離拒絕',!prepare(work,req('extract')).ok);
check('已安裝不可再安裝',!prepare(work,req('attach','RigidGroup',{module:'Driver',output:'side'})).ok);
check('循環安裝拒絕',!prepare(detached.candidateSnapshot,req('attach','RigidGroup',{module:'RigidGroup',output:'side'})).ok);
let current=structuredClone(source),undo=[];
const session=createRigidGroupInterfaceSession({getSnapshot:()=>current,applySnapshot:w=>{undo.push(current);current=w;}});
session.prepare(req('extract','Driver'));session.cancel();check('取消不改正式作品',!session.confirm().ok&&JSON.stringify(current)===before);
session.prepare(req('extract','Driver'));current.params.extra=1;check('來源變更拒絕舊候選',!session.confirm().ok&&undo.length===0);delete current.params.extra;
session.prepare(req('extract','Driver'));check('確認只新增一筆復原',session.confirm().ok&&undo.length===1);current=undo.pop();check('復原還原整份來源',JSON.stringify(current)===before);
const elsewhere=structuredClone(detached.candidateSnapshot);
elsewhere.comps.push({id:'Other',type:'bar',moduleId:'Other',p1:{id:'OtherA',type:'fixed',x:200,y:40},p2:{id:'OtherB',type:'fixed',x:240,y:40},lenParam:'OtherLength'});
elsewhere.params.OtherLength=40;
elsewhere.modules.push({id:'Other',name:'另一安裝座',base:'OtherA',outputs:[{id:'out',at:'OtherA',body:{kind:'bar',id:'Other'}}],mount:null});
const other=prepare(elsewhere,req('attach','RigidGroup',{module:'Other',output:'out'}));
check('可接到不同位置的輸出端',other.ok);
if(other.ok){const a=parts(detached.candidateSnapshot,0),b=parts(other.candidateSnapshot,0);check('四板整組平移保持相對位置',a.every(p=>{const q=b.find(v=>v.partId===p.partId);return p.pose.matrix.every((v,i)=>Math.abs(q.pose.matrix[i]-v-(i===12?200:i===13?40:0))<1e-6);}));}
check('缺失輸出端拒絕',!prepare(detached.candidateSnapshot,req('attach','RigidGroup',{module:'Driver',output:'missing'})).ok);
const ungrouped=structuredClone(work);delete ungrouped.modules.find(m=>m.id==='RigidGroup').rigidGroups;
check('解散名稱群組不使有效料斗失效',validate(ungrouped).ok);
check('分享重開仍通過料斗驗證',validate(normalizeSnapshot(decodeShareString(encodeSnapshot(work)))).ok);
report('rigid-group-interface');
